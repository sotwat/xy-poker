export type Translate = (key: string, variables?: Record<string, string | number>) => string;

export function translate(language: Language, key: string, variables: Record<string, string | number> = {}): string {
    const template = messages[language][key] ?? messages.en[key] ?? key;
    return Object.entries(variables).reduce(
        (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
        template,
    );
}

export function getMissingTranslationKeys(language: Language): string[] {
    const referenceLanguage: Language = language === 'ja' ? 'en' : 'ja';
    return Object.keys(messages[referenceLanguage]).filter(key => !(key in messages[language]));
}

export function resolveInitialLanguage(storage?: Pick<Storage, 'getItem'>): Language {
    try {
        return storage?.getItem(STORAGE_KEY) === 'en' ? 'en' : 'ja';
    } catch {
        return 'ja';
    }
}

